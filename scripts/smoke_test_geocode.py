"""Ручная проверка реального геокодирования через Nominatim.

Запуск из корня репозитория: python -m scripts.smoke_test_geocode

Требует интернет. Не входит в автоматические тесты (pytest) из-за
недетерминированности и rate-limit в 1 запрос/сек у Nominatim.

Адреса ниже подобраны так, чтобы покрыть реальным сетевым запросом разные
сокращения из normalize_address_for_nominatim (geocode.py): ул./пр-кт./д.
(первые два адреса, покрыты автотестами), пер./стр., б-р., наб., город-без-
Москвы (г.). Последний адрес — заведомо несуществующий, для проверки
фолбэка.
"""
from geocode import Geocoder

ADDRESSES = [
    ("Город Москва, пр-кт.Волгоградский, д. 128 к 5", "Кузьминки"),
    ("Город Москва, ул.Окская, д. 32", "Кузьминки"),
    ("Город Москва, ул.Международная, д. 28 стр. 1", "Таганский"),
    ("Город Москва, б-р.Чонгарский, д. 22 к 2", "Зюзино"),
    ("Город Москва, наб.Нагатинская, д. 60 к 2", "Нагатинский Затон"),
    ("г.Домодедово, ул.Советская, д. 5", None),
    ("Совсем несуществующий адрес 12345", "Несуществующий район"),
]


def main() -> None:
    geocoder = Geocoder()
    for address, district in ADDRESSES:
        result = geocoder.geocode_address(address, district)
        print(f"{address!r} -> lat={result.lat}, lon={result.lon}, source={result.source}")


if __name__ == "__main__":
    main()
